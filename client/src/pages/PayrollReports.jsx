function StatusPill({ status }) {
  const MAP = {
    paid: 'bg-emerald-50 text-emerald-700', locked: 'bg-slate-100 text-slate-600',
    approved: 'bg-blue-50 text-blue-700',   verified: 'bg-violet-50 text-violet-700',
    completed: 'bg-teal-50 text-teal-700',  failed: 'bg-red-50 text-red-700',
  };
  return <span className={`text-[0.65rem] font-bold px-2 py-0.5 rounded-full ${MAP[status] || 'bg-gray-100 text-gray-600'}`}>{status}</span>;
}

export default function PayrollReports() {
  const toast = useToast();
  const { selectedBranchId, selectedBranch } = useBranch();
  const branchLabel = selectedBranch?.name || 'All Branches';

  const now   = new Date();
  const [type,  setType]  = useState('summary');
  const [month, setMonth] = useState(now.getMonth() + 1);
  const [year,  setYear]  = useState(now.getFullYear());

  const activeReport = REPORT_TYPES.find(r => r.key === type);
  const cols         = COLUMNS[type] || [];

  const { data, isLoading, refetch } = useQuery({
    queryKey: ['payroll-report', type, month, year, selectedBranchId],
    queryFn:  () => apiGet(activeReport.endpoint, {
      month: month || undefined,
      year:  year  || undefined,
    }),
    enabled: Boolean(activeReport),
  });

  const rows = Array.isArray(data) ? data : [];

  async function downloadCsv() {
    try {
      const qs = { format: 'csv' };
      if (month) qs.month = month;
      if (year)  qs.year  = year;
      const blob = await apiDownload(activeReport.endpoint, qs);
      if (!blob || blob.size === 0) {
        toast('No data available to export for the selected period.', 'warning');
        return;
      }
      const url  = URL.createObjectURL(blob);
      const a    = document.createElement('a');
      a.href     = url;
      a.download = `${type}_${month || 'all'}_${year}.csv`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      setTimeout(() => URL.revokeObjectURL(url), 200);
    } catch (e) {
      const msg = e.message || 'Export failed. Please try again.';
      toast(msg.includes('permission') ? 'You do not have permission to export payroll reports.' : msg, 'error');
    }
  }

  return (
    <div className="space-y-5">
      {/* Header */}
      <div className="page-header">
        <div>
          <div className="page-title">Payroll Reports</div>
          <div className="page-subtitle flex items-center gap-2">
            <span className="text-[#777587]">Payroll</span>
            <span className="mx-1.5 text-[#c7c4d8]">›</span>
            Reports
            <span className="inline-flex items-center gap-1 text-xs font-bold px-2 py-0.5 rounded-full bg-[#f0f3ff] text-[#3525cd]">
              <GitBranch size={10} />
              {branchLabel}
            </span>
          </div>
        </div>
        <div className="flex items-center gap-2">
          <button onClick={() => refetch()}
            className="flex items-center gap-1.5 px-3 py-2 rounded-lg text-sm font-semibold text-[#464555] border border-[#c7c4d8] bg-white hover:bg-[#f0f3ff] transition-all">
            <RefreshCw size={13} /> Refresh
          </button>
          <button onClick={downloadCsv}
            className="flex items-center gap-1.5 px-4 py-2 rounded-lg text-sm font-bold bg-[#3525cd] text-white hover:bg-[#2a1fb0] transition-all shadow-sm">
            <Download size={14} /> Export CSV
          </button>
        </div>
      </div>

      {/* Report type selector + filters */}
      <div className="bg-white rounded-xl border border-[#e2e0f0] shadow-sm p-4">
        <div className="flex flex-wrap gap-2 mb-4">
          {REPORT_TYPES.map(r => (
            <button key={r.key}
              onClick={() => setType(r.key)}
              className={cn(
                'flex items-center gap-2 px-3 py-2 rounded-lg text-sm font-semibold border transition-all',
                type === r.key
                  ? 'bg-[#3525cd] text-white border-[#3525cd]'
                  : 'bg-white text-[#464555] border-[#c7c4d8] hover:border-[#3525cd]/40 hover:bg-[#f0f3ff]'
              )}>
              <r.Icon size={13} />
              {r.label}
            </button>
          ))}
        </div>

        {/* Period filter */}
        <div className="flex items-center gap-3 pt-3 border-t border-[#f0f3ff]">
          <span className="text-xs font-bold text-[#777587]">Period:</span>
          <select
            value={month}
            onChange={e => setMonth(Number(e.target.value))}
            className="border border-[#c7c4d8] rounded-lg px-2.5 py-1.5 text-sm focus:outline-none focus:border-[#3525cd] bg-white">
            <option value={0}>All months</option>
            {MONTHS.map((m, i) => <option key={i} value={i + 1}>{m}</option>)}
          </select>
          <div className="flex items-center gap-1 bg-white border border-[#c7c4d8] rounded-lg px-2 py-1.5">
            <button onClick={() => setYear(y => y - 1)} className="w-6 h-6 flex items-center justify-center text-[#777587] hover:text-[#3525cd]">‹</button>
            <span className="font-black text-sm text-[#151c27] min-w-[3rem] text-center">{year}</span>
            <button onClick={() => setYear(y => y + 1)} className="w-6 h-6 flex items-center justify-center text-[#777587] hover:text-[#3525cd]">›</button>
          </div>
          <span className="text-xs text-[#777587] ml-auto">{rows.length} row{rows.length !== 1 ? 's' : ''}</span>
        </div>
      </div>

      {/* Data table */}
      <div className="bg-white rounded-xl border border-[#e2e0f0] shadow-sm overflow-hidden">
        {isLoading ? (
          <div className="flex items-center justify-center py-16">
            <div className="w-6 h-6 border-2 border-[#3525cd]/30 border-t-[#3525cd] rounded-full animate-spin" />
          </div>
        ) : rows.length === 0 ? (
          <div className="flex flex-col items-center justify-center py-16 text-center">
            <BarChart3 size={36} className="text-[#c7c4d8] mb-3" />
            <p className="font-semibold text-[#464555]">No data for this period</p>
            <p className="text-sm text-[#777587] mt-1">Try a different month, year, or report type.</p>
          </div>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-sm">
              <thead>
                <tr className="border-b border-[#f0f3ff] bg-[#fafaff]">
                  {cols.map(c => (
                    <th key={c.key} className="text-left px-4 py-3 text-[0.65rem] font-black uppercase tracking-widest text-[#777587] whitespace-nowrap">
                      {c.label}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {rows.map((row, i) => (
                  <tr key={i} className={cn('border-b border-[#f9f9ff] hover:bg-[#fafaff] transition-colors', i % 2 === 0 ? 'bg-white' : 'bg-[#fafaff]')}>
                    {cols.map(c => {
                      const val = row[c.key];
                      const displayed = c.render ? c.render(val, row) : (val ?? '—');
                      return (
                        <td key={c.key} className={cn('px-4 py-2.5 whitespace-nowrap', c.bold ? 'font-bold text-[#151c27]' : 'text-[#464555]')}>
                          {displayed}
                        </td>
                      );
                    })}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
}
