import React, { useState } from 'react';
import { useQuery } from '@tanstack/react-query';
import {
  BarChart3, Download, FileText, Building2, AlertTriangle,
  PlusCircle, RefreshCw, GitBranch,
} from 'lucide-react';
import { useBranch } from '@/context/BranchContext';
import { useToast } from '@/context/ToastContext';
import { apiGet, apiDownload } from '@/lib/api';
import { MONTHS, cn } from '@/lib/utils';

const fmt  = n => '₹' + Number(n || 0).toLocaleString('en-IN', { minimumFractionDigits: 0 });
const fmtN = n => Number(n || 0).toLocaleString('en-IN', { minimumFractionDigits: 2 });

const REPORT_TYPES = [
  { key: 'summary',         label: 'Payroll Summary',    Icon: BarChart3,     endpoint: '/payroll/reports/summary' },
  { key: 'department',      label: 'Department Summary', Icon: Building2,     endpoint: '/payroll/reports/department' },
  { key: 'salary-register', label: 'Salary Register',    Icon: FileText,      endpoint: '/payroll/reports/salary-register' },
  { key: 'lop',             label: 'LOP Report',         Icon: AlertTriangle, endpoint: '/payroll/reports/lop' },
  { key: 'adjustments',     label: 'Adjustments',        Icon: PlusCircle,    endpoint: '/payroll/reports/adjustments' },
];

// ── Column definitions per report type ───────────────────────────────────────
